"""PlatformIO pre-build script: write the git commit and version of the build into include/git_version.h.

The board reports them as `gitCommit` and `firmwareVersion` (/api/boiler/status, console STATUS, boot banner),
so a test run on the board can be tied to a commit. "-dirty" means firmware inputs had uncommitted changes.
The version is 1.MM.DD.NN (FR-21): month and day of the last commit that changed a firmware input, and the
count of such commits on that day up to it. The header is rewritten only when it changes, so unchanged builds
do not recompile.

Runs from platformio.ini (extra_scripts = pre:tools/sh_git_version.py) or standalone:
    python tools/sh_git_version.py
"""
import os
import subprocess

HEADER = os.path.join("include", "git_version.h")
# Paths whose uncommitted changes make the binary (or its test result) differ from the commit: tools/ holds the
# pre-build scripts that shape the binary and the system test. docs/process.md §6.
FIRMWARE_INPUTS = ("src", "include", "web", "lib", "tools", "platformio.ini")


def _git(root, *args):
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def firmware_commit(root):
    """Short commit of HEAD, '-dirty' if firmware inputs have uncommitted changes, 'unknown' without git."""
    try:
        head = _git(root, "rev-parse", "--short=7", "HEAD")
        dirty = _git(root, "status", "--porcelain", "--", *FIRMWARE_INPUTS)
    except OSError:
        return "unknown"
    if not head:
        return "unknown"
    return head + ("-dirty" if dirty else "")


def firmware_version(root, rev="HEAD"):
    """FR-21: '1.MM.DD.NN' for the firmware at `rev`, '1.00.00.00' without git or firmware history."""
    try:
        dates = _git(root, "log", rev, "--format=%cd", "--date=format:%m.%d", "--", *FIRMWARE_INPUTS)
    except OSError:
        dates = None
    if not dates:
        return "1.00.00.00"
    days = dates.splitlines()
    # git log lists the newest first: the day of the last firmware commit and how many commits that day had
    count = 0
    for day in days:
        if day != days[0]:
            break
        count += 1
    return f"1.{days[0]}.{count:02d}"


def write_header(root):
    commit = firmware_commit(root)
    version = firmware_version(root)
    content = ("// AUTO-GENERATED by tools/sh_git_version.py - DO NOT EDIT\n"
               "#pragma once\n"
               f'#define APP_GIT_COMMIT "{commit}"\n'
               f'#define APP_VERSION "{version}"\n')
    dst = os.path.join(root, HEADER)
    old = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
    if old != content:
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    print(f"[sh_git_version] version {version}, commit {commit}")


# Only the PlatformIO names are guarded: a NameError inside write_header must fail the build, not skip it.
try:
    Import("env")  # noqa: F821 (provided by PlatformIO/SCons)
    PROJECT_DIR = str(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    PROJECT_DIR = None

if PROJECT_DIR:
    write_header(PROJECT_DIR)
elif __name__ == "__main__":
    write_header(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
