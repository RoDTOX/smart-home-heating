"""PlatformIO pre-build script: write the git commit of the build into include/git_version.h.

The board reports it as `gitCommit` (/api/boiler/status, console STATUS, boot banner), so a test run
on the board can be tied to a commit. "-dirty" means firmware inputs had uncommitted changes.
The header is rewritten only when the commit changes, so unchanged builds do not recompile.

Runs from platformio.ini (extra_scripts = pre:tools/sh_git_version.py) or standalone:
    python tools/sh_git_version.py
"""
import os
import subprocess

HEADER = os.path.join("include", "git_version.h")
# Paths whose uncommitted changes make the binary differ from the commit.
FIRMWARE_INPUTS = ("src", "include", "web", "lib", "platformio.ini")


def _git(root, *args):
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def firmware_commit(root):
    """Short commit of HEAD, '-dirty' if firmware inputs have uncommitted changes, 'unknown' without git."""
    try:
        head = _git(root, "rev-parse", "--short=7", "HEAD")
        dirty = _git(root, "status", "--porcelain", "--", *FIRMWARE_INPUTS)
    except OSError:
        return "unknown"
    if not head:
        return "unknown"
    return head + ("-dirty" if dirty else "")


def write_header(root):
    commit = firmware_commit(root)
    content = ("// AUTO-GENERATED by tools/sh_git_version.py - DO NOT EDIT\n"
               "#pragma once\n"
               f'#define APP_GIT_COMMIT "{commit}"\n')
    dst = os.path.join(root, HEADER)
    old = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
    if old != content:
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    print(f"[sh_git_version] commit {commit}")


try:
    Import("env")  # noqa: F821 (provided by PlatformIO/SCons)
    write_header(str(env["PROJECT_DIR"]))  # noqa: F821
except NameError:
    if __name__ == "__main__":
        write_header(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
