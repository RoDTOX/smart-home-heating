import os
from PIL import Image, ImageDraw

def make_pro_icon(target_size):
    s = target_size * 4
    img = Image.new('RGBA', (s, s), (8, 12, 20, 255))
    draw = ImageDraw.Draw(img)
    
    pad = int(s * 0.08)
    radius = int(s * 0.22)
    draw.rounded_rectangle([pad, pad, s - pad, s - pad], radius=radius, fill=(15, 23, 42, 255), outline=(56, 189, 248, 160), width=max(4, s // 70))
    
    cx, cy = s // 2, int(s * 0.54)
    import math
    
    outer_pts = []
    for deg in range(0, 360, 5):
        rad = math.radians(deg)
        r_base = s * 0.26
        if deg < 180:
            r = r_base * (0.85 + 0.15 * math.sin(rad))
        else:
            diff = abs(deg - 270)
            r = r_base * ((diff / 90.0) ** 1.3)
        
        px = cx + r * math.cos(rad)
        py = cy + r * math.sin(rad) * 1.15
        outer_pts.append((px, py))
    
    draw.polygon(outer_pts, fill=(249, 115, 22, 255))
    
    mid_pts = []
    for px, py in outer_pts:
        mid_pts.append((cx + (px - cx) * 0.65, cy + (py - cy) * 0.65 + s * 0.03))
    draw.polygon(mid_pts, fill=(234, 179, 8, 255))
    
    core_pts = []
    for px, py in outer_pts:
        core_pts.append((cx + (px - cx) * 0.32, cy + (py - cy) * 0.32 + s * 0.06))
    draw.polygon(core_pts, fill=(56, 189, 248, 255))

    res = img.resize((target_size, target_size), Image.Resampling.LANCZOS)
    return res

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    root_dir = os.path.dirname(script_dir)
    web_dir = os.path.join(root_dir, "web")
    inc_dir = os.path.join(root_dir, "include")

    i192 = make_pro_icon(192).quantize(colors=16, method=Image.Quantize.FASTOCTREE)
    i192_path = os.path.join(web_dir, "icon-192.png")
    i192.save(i192_path, optimize=True)

    with open(i192_path, "rb") as f:
        b192 = f.read()

    print(f"Generated icon-192.png: {len(b192)} bytes")

    header_content = [
        "// Auto-generated by tools/generate_icons.py - DO NOT EDIT MANUALLY",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        f"// PWA App Icon 192x192 PNG ({len(b192)} bytes)",
        f"static const size_t ICON_192_PNG_LEN = {len(b192)};",
        "static const uint8_t PROGMEM ICON_192_PNG[] = {"
    ]

    for i in range(0, len(b192), 16):
        chunk = b192[i:i+16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        header_content.append(f"  {hex_str},")
    header_content.append("};")
    header_content.append("")

    header_path = os.path.join(inc_dir, "pwa_icons.h")
    with open(header_path, "w", encoding="utf-8") as f:
        f.write("\n".join(header_content))

    print(f"Wrote {header_path}")

if __name__ == "__main__":
    main()
