"""PlatformIO pre-build script: derive build number and git commit for include/Version.h.

Writes include/git_version.h (gitignored) only when its content changes, so unchanged
builds do not trigger recompiles.
"""
import os
import sys

try:
    Import("env")  # noqa: F821 (provided by PlatformIO/SCons)
    PROJECT_DIR = str(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

tools_dir = os.path.join(str(PROJECT_DIR), "tools")
if tools_dir not in sys.path:
    sys.path.insert(0, tools_dir)
if str(PROJECT_DIR) not in sys.path:
    sys.path.insert(0, str(PROJECT_DIR))

try:
    from tools.version_helper import get_version_info
except ImportError:
    from version_helper import get_version_info

info = get_version_info(PROJECT_DIR)
version = info["version"]
daily_rev = info["daily_rev"]
total_commits = info["total_commits"]
commit = info["commit"]
build_date = info["build_date"]
build_time = info["build_time"]

content = (
    "// AUTO-GENERATED by tools/git_version.py - DO NOT EDIT\n"
    "#pragma once\n"
    f'#define APP_VERSION "{version}"\n'
    f"#define APP_BUILD_NUMBER {daily_rev}\n"
    f"#define APP_TOTAL_COMMITS {total_commits}\n"
    f'#define APP_GIT_COMMIT "{commit}"\n'
    f'#define APP_BUILD_DATE "{build_date}"\n'
    f'#define APP_BUILD_TIME "{build_time}"\n'
)

dst = os.path.join(PROJECT_DIR, "include", "git_version.h")
old = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
if old != content:
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)

print(f"[git_version] Version: {version}, commit: {commit}, date: {build_date} {build_time}")
